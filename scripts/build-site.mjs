// Packs everything in public/ into src/site.generated.js, so the Worker serves the
// website itself. Runs automatically before `wrangler deploy` and `wrangler dev`.
//
// Why not Cloudflare's separate static-asset upload: that upload authenticates with a
// short-lived second token, which the network proxy of cloud coding sessions replaces
// with the saved API token, so it fails there. Bundling works everywhere.

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative, extname } from "node:path";

const ROOT = "public";
const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".woff2": "font/woff2",
  ".png": "image/png",
  ".ico": "image/x-icon",
};
const TEXT = new Set([".html", ".css", ".js", ".mjs", ".svg", ".json"]);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const entries = [];
for (const file of walk(ROOT).sort()) {
  const ext = extname(file).toLowerCase();
  if (!TYPES[ext]) continue;
  const bytes = readFileSync(file);
  const etag = `"${createHash("sha256").update(bytes).digest("hex").slice(0, 20)}"`;
  const path = "/" + relative(ROOT, file).split("\\").join("/");
  const body = TEXT.has(ext) ? { text: bytes.toString("utf8") } : { base64: bytes.toString("base64") };
  entries.push([path, { type: TYPES[ext], etag, ...body }]);
}

const out =
  "// Generated by scripts/build-site.mjs from public/. Do not edit.\n" +
  `export default ${JSON.stringify(Object.fromEntries(entries))};\n`;
writeFileSync("src/site.generated.js", out);
console.log(`site: packed ${entries.length} files (${(out.length / 1048576).toFixed(2)} MB)`);
